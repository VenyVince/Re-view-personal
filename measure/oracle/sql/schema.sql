WHENEVER SQLERROR EXIT FAILURE

-- Columns are the ones named by mapper INSERT and SELECT.
-- ORDER_STATUS default literal is not in the app repo. CREATED lets INSERT ... DEFAULT succeed.
-- ADDRESS and PAYMENT_METHODS are outside the measurement table list, so those ids are nullable and have no foreign key.
-- REVIEW_LIKE is outside the list. Planned queries do not join it.

CREATE TABLE baumann (
    baumann_id NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    type       VARCHAR2(20) NOT NULL,
    first      VARCHAR2(10),
    second     VARCHAR2(10),
    third      VARCHAR2(10),
    fourth     VARCHAR2(10)
);

CREATE TABLE user_table (
    user_id      NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    id           VARCHAR2(50)  NOT NULL,
    password     VARCHAR2(200) NOT NULL,
    name         VARCHAR2(50)  NOT NULL,
    email        VARCHAR2(100) NOT NULL,
    nickname     VARCHAR2(50)  NOT NULL,
    phone_number VARCHAR2(30)  NOT NULL,
    baumann_id   NUMBER        NOT NULL,
    role         VARCHAR2(20)  DEFAULT 'USER' NOT NULL,
    point        NUMBER        DEFAULT 0 NOT NULL,
    CONSTRAINT uk_user_login UNIQUE (id),
    CONSTRAINT fk_user_baumann FOREIGN KEY (baumann_id) REFERENCES baumann (baumann_id)
);

CREATE TABLE product (
    product_id   NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    prd_name     VARCHAR2(200) NOT NULL,
    prd_brand    VARCHAR2(100) NOT NULL,
    ingredient   VARCHAR2(1000),
    description  VARCHAR2(1000),
    price        NUMBER(10)    NOT NULL,
    category     VARCHAR2(50),
    stock        NUMBER        DEFAULT 0 NOT NULL,
    rating       NUMBER(3,1)   DEFAULT 0 NOT NULL,
    review_count NUMBER        DEFAULT 0 NOT NULL,
    baumann_id   NUMBER        NOT NULL,
    is_sold_out  VARCHAR2(1)   DEFAULT '0' NOT NULL,
    created_at   DATE          DEFAULT SYSDATE NOT NULL,
    updated_at   DATE,
    deleted_at   DATE,
    CONSTRAINT fk_product_baumann FOREIGN KEY (baumann_id) REFERENCES baumann (baumann_id)
);

CREATE TABLE product_image (
    prd_img_id   NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    product_id   NUMBER        NOT NULL,
    image_url    VARCHAR2(500) NOT NULL,
    is_thumbnail VARCHAR2(1)   NOT NULL,
    CONSTRAINT fk_pimg_product FOREIGN KEY (product_id) REFERENCES product (product_id)
);

CREATE TABLE orders (
    order_id     NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    order_no     VARCHAR2(50) NOT NULL,
    user_id      NUMBER       NOT NULL,
    address_id   NUMBER,
    payment_id   NUMBER,
    total_price  NUMBER(10)   NOT NULL,
    used_point   NUMBER       DEFAULT 0 NOT NULL,
    order_status VARCHAR2(30) DEFAULT 'CREATED' NOT NULL,
    created_at   DATE         DEFAULT SYSDATE NOT NULL,
    delivery_num VARCHAR2(50),
    CONSTRAINT fk_orders_user FOREIGN KEY (user_id) REFERENCES user_table (user_id)
);

CREATE TABLE order_item (
    order_item_id NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    order_id      NUMBER        NOT NULL,
    product_id    NUMBER        NOT NULL,
    product_name  VARCHAR2(200) NOT NULL,
    product_price NUMBER(10)    NOT NULL,
    quantity      NUMBER        NOT NULL,
    CONSTRAINT fk_item_order FOREIGN KEY (order_id) REFERENCES orders (order_id),
    CONSTRAINT fk_item_product FOREIGN KEY (product_id) REFERENCES product (product_id)
);

CREATE TABLE review (
    review_id     NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    product_id    NUMBER        NOT NULL,
    user_id       NUMBER        NOT NULL,
    content       VARCHAR2(1000) NOT NULL,
    rating        NUMBER(2,1)   NOT NULL,
    created_at    DATE          DEFAULT SYSDATE NOT NULL,
    updated_at    DATE,
    deleted_at    DATE,
    order_item_id NUMBER,
    like_count    NUMBER        DEFAULT 0 NOT NULL,
    dislike_count NUMBER        DEFAULT 0 NOT NULL,
    is_checked    NUMBER        DEFAULT 0 NOT NULL,
    is_selected   VARCHAR2(1)   DEFAULT '0' NOT NULL,
    CONSTRAINT fk_review_product FOREIGN KEY (product_id) REFERENCES product (product_id),
    CONSTRAINT fk_review_user FOREIGN KEY (user_id) REFERENCES user_table (user_id),
    CONSTRAINT fk_review_item FOREIGN KEY (order_item_id) REFERENCES order_item (order_item_id)
);

CREATE SEQUENCE review_images_seq START WITH 1;

CREATE TABLE review_images (
    review_image_id NUMBER DEFAULT review_images_seq.NEXTVAL PRIMARY KEY,
    review_id       NUMBER        NOT NULL,
    image_url       VARCHAR2(500) NOT NULL,
    CONSTRAINT fk_rimg_review FOREIGN KEY (review_id) REFERENCES review (review_id)
);

CREATE SEQUENCE seq_review_comment START WITH 1;

CREATE TABLE review_comment (
    review_comment_id NUMBER DEFAULT seq_review_comment.NEXTVAL PRIMARY KEY,
    review_id         NUMBER         NOT NULL,
    user_id           NUMBER         NOT NULL,
    content           VARCHAR2(1000) NOT NULL,
    created_at        DATE           DEFAULT SYSDATE NOT NULL,
    deleted_at        DATE,
    CONSTRAINT fk_comment_review FOREIGN KEY (review_id) REFERENCES review (review_id),
    CONSTRAINT fk_comment_user FOREIGN KEY (user_id) REFERENCES user_table (user_id)
);

CREATE TABLE point_history (
    point_history_id NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    user_id          NUMBER       NOT NULL,
    amount           NUMBER       NOT NULL,
    type             VARCHAR2(10) NOT NULL,
    created_at       DATE         DEFAULT SYSDATE NOT NULL,
    description      VARCHAR2(200),
    review_id        NUMBER,
    CONSTRAINT fk_point_user FOREIGN KEY (user_id) REFERENCES user_table (user_id),
    CONSTRAINT fk_point_review FOREIGN KEY (review_id) REFERENCES review (review_id)
);

EXIT
