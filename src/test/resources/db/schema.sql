CREATE OR REPLACE EDITIONABLE TRIGGER "REVIEW_TEST"."TR_REVIEW_RATING_DELETE"
    FOR DELETE ON review
    COMPOUND TRIGGER

    TYPE t_pid_tab IS TABLE OF review.product_id%TYPE;
    g_pid_tab t_pid_tab := t_pid_tab();

AFTER EACH ROW IS
BEGIN
    -- 삭제된 product_id를 모아둠
    g_pid_tab.EXTEND;
    g_pid_tab(g_pid_tab.LAST) := :OLD.product_id;
END AFTER EACH ROW;

    AFTER STATEMENT IS
    BEGIN
        -- 모든 DELETE가 끝난 뒤에 product 테이블 갱신
	FOR i IN 1 .. g_pid_tab.COUNT LOOP
		UPDATE product p
		SET rating = (
		    SELECT ROUND(AVG(rating), 1)
		    FROM review r
		    WHERE r.product_id = g_pid_tab(i)
		      AND r.deleted_at IS NULL
		)
		WHERE p.product_id = g_pid_tab(i);
	    END LOOP;
    END AFTER STATEMENT;

    END TR_REVIEW_RATING_DELETE;
/
ALTER TRIGGER "REVIEW_TEST"."TR_REVIEW_RATING_DELETE" ENABLE;

