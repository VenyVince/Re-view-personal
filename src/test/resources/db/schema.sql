-- triggers

CREATE OR REPLACE EDITIONABLE TRIGGER "REVIEW_TEST"."ORDERS_BI_TRG"
    before insert
    on REVIEW_TEST.ORDERS
    for each row
BEGIN
  -- :NEW는 새로 INSERT될 행을 의미합니다.
  -- :NEW.ORDER_ID에 시퀀스의 다음 값을 할당합니다.
  :NEW.ORDER_ID := ORDERS_SEQ.NEXTVAL;
END;
/
ALTER TRIGGER "REVIEW_TEST"."ORDERS_BI_TRG" ENABLE;

CREATE OR REPLACE EDITIONABLE TRIGGER "REVIEW_TEST"."POINT_HISTORY_ID_TRG"
    before insert
    on REVIEW_TEST.POINT_HISTORY
    for each row
BEGIN
    -- POINT_HISTORY_ID에 값이 명시적으로 제공되지 않은 경우에만 시퀀스 값을 할당합니다.
    IF :NEW.POINT_HISTORY_ID IS NULL THEN
	SELECT POINT_HISTORY_ID_SEQ.NEXTVAL
	INTO :NEW.POINT_HISTORY_ID
	FROM DUAL;
    END IF;
END;
/
ALTER TRIGGER "REVIEW_TEST"."POINT_HISTORY_ID_TRG" ENABLE;

CREATE OR REPLACE EDITIONABLE TRIGGER "REVIEW_TEST"."PRODUCT_BI"
    before insert
    on REVIEW_TEST.PRODUCT
    for each row
BEGIN
    IF :NEW.product_id IS NULL THEN        -- product_id가 NULL이면
        :NEW.product_id := product_seq.NEXTVAL;  -- 자동으로 SEQUENCE 값 할당
    END IF;
END;
/
ALTER TRIGGER "REVIEW_TEST"."PRODUCT_BI" ENABLE;

